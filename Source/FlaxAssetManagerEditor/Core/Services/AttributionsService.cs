using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using FlaxEngine;
using FlaxAssetManager.Core.Models;
using FlaxAssetManager.Core.Utils;

namespace FlaxAssetManager.Core.Services
{
    /// <summary>
    /// Writes <c>Content/FlaxAssetManager/ATTRIBUTIONS.md</c> from the install records.
    /// <para>
    /// The point of installing an asset pack is that the asset arrives; the point of a license is that
    /// some of them ask for something back when the game ships. CC-BY (Game Icons, Twemoji, part of
    /// SoundBible) asks for credit to the creator. Apache-2.0 (Material Icons) asks that the license and
    /// any NOTICE stay with the distributed files. Quaternius's license sells nothing but forbids
    /// redistributing the assets themselves. None of that is satisfiable from a UI label: by shipping
    /// time the source may be gone from <c>Sources.json</c>, and the catalog may have re-labeled the pack.
    /// </para>
    /// <para>
    /// So the plugin snapshots the obligation into the project at install time — the install record
    /// carries license, author, credit line and the source's website — and renders it here, one line per
    /// installed pack, grouped by source. It is a working list to copy credits from, generated from
    /// <c>.installed.json</c> on every install and remove, and it says so on itself.
    /// </para>
    /// <para>
    /// It is not legal advice and does not claim to be complete: it lists what this plugin installed.
    /// Assets added by hand, engine runtime files, FMOD, middleware and engine royalties are outside
    /// what a package manager can see.
    /// </para>
    /// </summary>
    public static class AttributionsService
    {
        /// <summary>Name of the generated file, inside the manager's content folder.</summary>
        public const string FileName = "ATTRIBUTIONS.md";

        /// <summary>
        /// The Markdown body. Split out from file I/O so the rendering can be asserted in a test without
        /// touching a project. Packs sort by source display name, then pack name, so the file has a stable
        /// diff: installing one pack changes one line, not the ordering of every group.
        /// </summary>
        public static string Render(InstalledManifest installed)
        {
            var sb = new StringBuilder();
            sb.AppendLine("# Asset attributions");
            sb.AppendLine();
            sb.AppendLine("Generated by **FlaxAssetManager** from the project's install records — do not edit by hand,");
            sb.AppendLine("it is rewritten on every install and remove. The source of truth is");
            sb.AppendLine("`Content/FlaxAssetManager/.installed.json`.");
            sb.AppendLine();
            sb.AppendLine("Each line is one pack installed by FlaxAssetManager, with the license, author and credit line");
            sb.AppendLine("the source manifest declared **at install time**. Copy what you need into your project's");
            sb.AppendLine("credits. The license text, not this file, decides what your build owes: some licenses ask");
            sb.AppendLine("for a credit line, some for the license text to travel with the files, some for the assets");
            sb.AppendLine("never to be redistributed on their own. Middleware, engine and hand-added assets are not");
            sb.AppendLine("listed here - a package manager only sees what it installed.");
            sb.AppendLine();

            var records = installed?.Installed;
            if (records == null || records.Count == 0)
            {
                sb.AppendLine("_Nothing installed by FlaxAssetManager in this project._");
                sb.AppendLine();
                sb.AppendLine($"Generated {DateTime.UtcNow:yyyy-MM-dd HH:mm} UTC.");
                return sb.ToString();
            }

            // Group by source, labelled by the name recorded at install time (the manifest may be gone by
            // the time the file is read), with the source website on the group header.
            var groups = new SortedDictionary<string, List<InstalledEntry>>(StringComparer.OrdinalIgnoreCase);
            for (int i = 0; i < records.Count; i++)
            {
                var e = records[i];
                if (e == null)
                    continue;
                var key = FirstNonEmpty(e.SourceName, e.SourceId, SafeHost(e.SourceUrl), "unknown source");
                if (!groups.TryGetValue(key, out var list))
                    groups[key] = list = new List<InstalledEntry>();
                list.Add(e);
            }

            foreach (var kv in groups)
            {
                var list = kv.Value;
                var website = FirstNonEmpty(list[0]?.SourceWebsite, list[0]?.SourceUrl);
                sb.Append("## ").Append(kv.Key);
                if (!string.IsNullOrWhiteSpace(website))
                    sb.Append(" — ").Append(website);
                sb.AppendLine();
                sb.AppendLine();
                list.Sort((a, b) => string.Compare(
                    FirstNonEmpty(a.PackName, a.PackId),
                    FirstNonEmpty(b.PackName, b.PackId),
                    StringComparison.OrdinalIgnoreCase));

                foreach (var e in list)
                {
                    sb.Append("- ").Append(CreditLine.Build(e));
                    sb.Append("  ·  v").Append(e.InstalledVersion ?? "?");
                    if (!string.IsNullOrWhiteSpace(e.InstallPath))
                        sb.Append("  ·  installed at `").Append(e.InstallPath).Append('`');
                    if (string.IsNullOrWhiteSpace(e.License))
                        sb.Append("  ·  **license not declared: check before shipping**");
                    sb.AppendLine();
                }
                sb.AppendLine();
            }

            sb.AppendLine($"Generated {DateTime.UtcNow:yyyy-MM-dd HH:mm} UTC from {records.Count} install record(s).");
            sb.AppendLine();
            return sb.ToString();
        }

        /// <summary>
        /// Writes <see cref="FileName"/> into <paramref name="folder"/>. Best-effort by contract: the
        /// caller has already installed the pack, and a failure to write a summary must not turn a good
        /// install into a reported failure. Returns the path written, or null.
        /// </summary>
        public static string TryWrite(string folder, InstalledManifest installed)
        {
            try
            {
                Directory.CreateDirectory(folder);
                var path = Path.Combine(folder, FileName);
                File.WriteAllText(path, Render(installed));
                return path;
            }
            catch (Exception e)
            {
                Debug.LogWarning($"FlaxAssetManager: installed pack(s) are recorded, but {FileName} could not be written: {e.Message}");
                return null;
            }
        }

        private static string FirstNonEmpty(params string[] values)
        {
            for (int i = 0; i < values.Length; i++)
                if (!string.IsNullOrWhiteSpace(values[i]))
                    return values[i];
            return null;
        }

        private static string SafeHost(string url)
        {
            if (string.IsNullOrWhiteSpace(url))
                return null;
            try
            {
                var host = new Uri(url).Host;
                return host.StartsWith("www.", StringComparison.OrdinalIgnoreCase) ? host.Substring(4) : host;
            }
            catch
            {
                return null;
            }
        }
    }
}
